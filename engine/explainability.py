"""
explainability.py -- Phase 6. "Why are you saying this?"

The owner must be able to take any statement the system made and walk back to the evidence:

    Question -> interpretation -> analyst role -> metric -> calculation -> source evidence
             -> validation -> trust decision -> reasoning -> recommendation

Nothing here computes anything. Every link is READ from an object an earlier stage already
produced, which is the point: if a link cannot be filled, that is a real gap in the chain and
the chain says so rather than narrating over it. answer_contract.md 2 makes the same point about
citations -- "A citation is not a footnote appended after the fact -- it is generated by the
same Execution step that produced the number" -- and this module is that principle applied to
the whole pipeline instead of to one figure.
"""
import re
from dataclasses import dataclass, field

from engine.result import NOT_DETERMINABLE_TEXT

# The chain's fixed links, in the order the Phase 6 brief 14 gives them.
LINK_QUESTION = "question"
LINK_INTERPRETATION = "interpretation"
LINK_ANALYST_ROLE = "analyst_role"
LINK_METRIC = "metric"
LINK_CALCULATION = "calculation"
LINK_EVIDENCE = "source_evidence"
LINK_VALIDATION = "validation"
LINK_TRUST = "trust_decision"
LINK_REASONING = "reasoning"
LINK_RECOMMENDATION = "recommendation"

ALL_LINKS = (LINK_QUESTION, LINK_INTERPRETATION, LINK_ANALYST_ROLE, LINK_METRIC,
             LINK_CALCULATION, LINK_EVIDENCE, LINK_VALIDATION, LINK_TRUST, LINK_REASONING,
             LINK_RECOMMENDATION)

# Links that are legitimately empty for some answers, with the condition under which that is so.
# A link outside this map that comes back empty is a defect, not a variation.
CONDITIONALLY_EMPTY = {
    LINK_RECOMMENDATION: "only present when the question asked for one, or an insight carried "
                         "one (business_reasoning_spec.md 3's ceiling table)",
    LINK_REASONING: "only present once a CALCULATION exists to reason about",
    LINK_CALCULATION: "absent when the question terminated before execution "
                      "(clarification, refusal, or a structural limitation)",
    LINK_EVIDENCE: "absent when nothing was computed",
    LINK_VALIDATION: "absent when nothing was computed",
    LINK_METRIC: "absent when no metric resolved",
}


@dataclass(frozen=True)
class ChainLink:
    name: str
    content: str
    source: str = ""            # the module/document this link was read from
    present: bool = True


@dataclass
class EvidenceChain:
    links: tuple = ()
    complete: bool = False
    gaps: tuple = ()

    def get(self, name):
        for l in self.links:
            if l.name == name:
                return l
        return None

    def render(self):
        out = ["WHY THIS ANSWER -- evidence chain", ""]
        for l in self.links:
            marker = "  " if l.present else "  (not applicable) "
            out.append(f"{marker}{l.name.upper()}: {l.content}")
            if l.source:
                out.append(f"      source: {l.source}")
        if self.gaps:
            out.append("")
            out.append("GAPS")
            for g in self.gaps:
                out.append(f"  - {g}")
        return "\n".join(out)


def build(result, routing=None):
    """Assemble the chain from a completed AskResult (Phase 4/5) plus its role routing."""
    links, gaps = [], []

    def add(name, content, source="", present=True):
        links.append(ChainLink(name=name, content=content, source=source, present=present))

    add(LINK_QUESTION, result.question, "the owner's own words")

    interp = []
    if result.llm_request is not None:
        r = result.llm_request
        interp.append(f"intent={list(r.intent)}")
        if r.concept:
            interp.append(f"concept={r.concept}")
        if r.time_range:
            interp.append(f"period={r.time_range}")
        if r.dimensions:
            interp.append(f"dimensions={list(r.dimensions)}")
    if result.inherited_context:
        interp.append(f"inherited from the previous turn: {list(result.inherited_context)}")
    add(LINK_INTERPRETATION, "; ".join(interp) or "no structured interpretation was produced",
        "structured_output.py (the model's proposal, after contract validation)",
        present=bool(interp))

    if routing is not None:
        add(LINK_ANALYST_ROLE,
            "; ".join(routing.explain()),
            "analyst_roles.py routing over the metric's domain and the question's intent")
    else:
        add(LINK_ANALYST_ROLE, "no lens routing recorded for this turn", present=False)

    if result.metric_ids:
        add(LINK_METRIC, ", ".join(result.metric_ids), "semantic_metric_registry.csv")
    else:
        add(LINK_METRIC, "no metric resolved", present=False)
        gaps.append(f"{LINK_METRIC}: {CONDITIONALLY_EMPTY[LINK_METRIC]}")

    calc, evidence, validation = [], [], []
    for a in result.answers:
        for r in a.results:
            calc.append(f"[{r.metric_id}/{r.definition_label}] "
                        f"{r.calculation_provenance[:220]}")
            evidence.extend(str(e) for e in r.evidence_sources[:6])
            validation.append(f"{r.metric_id}: {r.validation_status}"
                              + (f" ({r.validation_reference[:120]})"
                                 if r.validation_reference else ""))

    add(LINK_CALCULATION, " | ".join(calc) or "nothing was computed",
        "analytics_execution_spec.md 3-7, applied by engine/calculators/",
        present=bool(calc))

    # Source lineage sits between evidence filenames and actual DB objects.
    # Never invent names — unresolved objects stay "Not determinable from exported evidence."
    lineage_bits = []
    if result.metric_ids:
        try:
            from engine import source_lineage as lineage_mod
            for mid in result.metric_ids[:3]:
                rec = lineage_mod.lineage_for_metric(mid)
                for ref in rec.source_objects[:4]:
                    lineage_bits.append(
                        f"{mid}:{ref.declared_name}→"
                        f"{ref.actual_source_object}"
                        f"[{ref.manifest_key}/{ref.lineage_confidence}]"
                    )
                if rec.date_basis:
                    lineage_bits.append(f"{mid}:date_basis={rec.date_basis[:80]}")
        except Exception:
            lineage_bits = []

    evidence_content = ", ".join(dict.fromkeys(evidence)) or "no evidence was read"
    if lineage_bits:
        evidence_content = evidence_content + " || lineage: " + "; ".join(lineage_bits)
    add(LINK_EVIDENCE, evidence_content,
        "evidence/file_manifest.csv + engine/source_lineage.py", present=bool(evidence) or bool(lineage_bits))
    add(LINK_VALIDATION, " | ".join(validation) or "nothing was validated",
        "validation_summary.csv (80 checks) via engine/validator.py",
        present=bool(validation))

    trust_bits = []
    if result.trust_level:
        trust_bits.append(f"trust_level={result.trust_level}")
    if result.plan is not None:
        trust_bits.append(f"headline_permitted={result.plan.headline_permitted}")
        if result.plan.trust_reason:
            trust_bits.append(result.plan.trust_reason[:200])
        if result.plan.required_disclosures:
            trust_bits.append(f"disclosures={list(result.plan.required_disclosures)}")
    add(LINK_TRUST, "; ".join(trust_bits) or "no trust verdict recorded",
        "engine/gate.py (Layer 3), ai_trust_policy.md", present=bool(trust_bits))

    reasoning = []
    if result.reasoning is not None:
        for s in result.reasoning.statements:
            reasoning.append(f"{s.stage}: {s.text[:180]}")
        if result.reasoning.ceiling_raised_for_disclosure:
            reasoning.append(
                f"(ceiling raised from {result.reasoning.intent_ceiling} to "
                f"{result.reasoning.ceiling} because a conflict disclosure is mandatory)")
    add(LINK_REASONING, " | ".join(reasoning) or "no reasoning stage ran",
        "business_reasoning_spec.md ladder via engine/business_reasoning.py",
        present=bool(reasoning))
    if not reasoning:
        gaps.append(f"{LINK_REASONING}: {CONDITIONALLY_EMPTY[LINK_REASONING]}")

    recs = []
    if result.reasoning is not None:
        recs = [s.text for s in result.reasoning.statements if s.stage == "RECOMMENDATION"]
    ds = getattr(result, "decision_support", None)
    if ds is not None and getattr(ds, "recommended_actions", ()):
        recs.extend(str(a) for a in ds.recommended_actions)
    add(LINK_RECOMMENDATION, " | ".join(recs) or "no recommendation was made",
        "business_reasoning_spec.md 2 RECOMMENDATION gating rule", present=bool(recs))
    if not recs:
        gaps.append(f"{LINK_RECOMMENDATION}: {CONDITIONALLY_EMPTY[LINK_RECOMMENDATION]}")

    for l in links:
        if not l.present and l.name not in CONDITIONALLY_EMPTY:
            gaps.append(f"{l.name}: empty, and this link has no documented empty case")

    required_present = all(
        (chain_link.present or chain_link.name in CONDITIONALLY_EMPTY)
        for chain_link in links)

    return EvidenceChain(links=tuple(links), complete=required_present, gaps=tuple(gaps))


def validate(chain: EvidenceChain):
    """Every link must be PRESENT or documented-as-conditionally-empty. Returns violations."""
    v = []
    names = [l.name for l in chain.links]
    for required in ALL_LINKS:
        if required not in names:
            v.append(f"chain is missing the {required!r} link entirely")
    for l in chain.links:
        if not l.present and l.name not in CONDITIONALLY_EMPTY:
            v.append(f"{l.name!r} is empty and has no documented empty case")
        if l.present and not l.content.strip():
            v.append(f"{l.name!r} claims to be present but carries no content")
        if l.present and l.name not in (LINK_QUESTION,) and not l.source:
            v.append(f"{l.name!r} cites no source module or document")
    return tuple(v)


